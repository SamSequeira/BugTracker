"""
Candidate Issue Generator

Takes findings generated by the Static Analyzer,
validates them, removes exact duplicates, and
returns clean CandidateIssue records.
"""

from typing import List, Dict, Any

from app.services.static_analyzer.models import CandidateIssue


# --------------------------------------------------
# VALIDATE CANDIDATE ISSUE
# --------------------------------------------------

def validate_candidate_issue(issue: CandidateIssue) -> bool:
    """
    Validate the minimum information required
    for a candidate issue.
    """

    if not issue.file_path.strip():
        return False

    if issue.line_number <= 0:
        return False

    if not issue.issue_type.strip():
        return False

    if not issue.message.strip():
        return False

    return True


# --------------------------------------------------
# REMOVE DUPLICATE ISSUES
# --------------------------------------------------

def remove_duplicate_issues(
    issues: List[CandidateIssue]
) -> List[CandidateIssue]:
    """
    Remove exact duplicate issues.

    Two issues are considered duplicates when they
    belong to the same file, line and rule.
    """

    unique_issues = []
    seen = set()

    for issue in issues:

        key = (
            issue.file_path,
            issue.line_number,
            issue.rule_id
        )

        if key not in seen:
            seen.add(key)
            unique_issues.append(issue)

    return unique_issues


# --------------------------------------------------
# GENERATE CANDIDATE ISSUES
# --------------------------------------------------

def generate_candidate_issues(
    issues: List[CandidateIssue]
) -> List[CandidateIssue]:
    """
    Validate and clean issues generated by StaticAnalyzer.

    Pipeline:

        StaticAnalyzer
              ↓
        CandidateIssue
              ↓
        Validation
              ↓
        Duplicate Removal
              ↓
        Clean Candidate Issues
    """

    valid_issues = []

    # Step 1: Validate
    for issue in issues:

        if validate_candidate_issue(issue):
            valid_issues.append(issue)

    # Step 2: Remove duplicates
    unique_issues = remove_duplicate_issues(valid_issues)

    return unique_issues


# --------------------------------------------------
# CONVERT TO API-FRIENDLY DICTIONARY
# --------------------------------------------------

def candidate_issues_to_dict(
    issues: List[CandidateIssue]
) -> List[Dict[str, Any]]:
    """
    Convert CandidateIssue objects into dictionaries
    suitable for API responses.
    """

    return [
        issue.to_dict()
        for issue in issues
    ]