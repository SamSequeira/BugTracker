# Demo fixture — one prepared bug scenario for the live demo
# ---------------------------------------------------------------------------

DEMO_BUG = {
    "rule_id": "PY_DIV_001",
    "file_path": "demo/calculator.py",
    "function_name": "divide",
    "description": (
        "Division by zero in demo/calculator.py::divide() — "
        "the divisor `b` is not validated before division."
    ),
    "source_code": """\
# demo/calculator.py
# This file intentionally contains a bug for demo purposes.

def divide(a, b):
    return a / b   # BUG: b could be zero
""",
}


def run_demo_escaped_check(repository_path: Optional[str] = None) -> EscapedTestingResult:
    """
    Run the escaped-testing check on the prepared demo bug.
    Returns an EscapedTestingResult ready for display.
    """
    from app.services.test_generation_service import test_generation_service

    harness = test_generation_service.generate_and_run(
        rule_id=DEMO_BUG["rule_id"],
        language="Python",
        code_snippet="return a / b",
    )
    gen_test = harness.generated_test_source

    detector = EscapedTestingDetector()
    return detector.check(
        rule_id=DEMO_BUG["rule_id"],
        file_path=DEMO_BUG["file_path"],
        function_name=DEMO_BUG["function_name"],
        repository_path=repository_path,
        generated_test_source=gen_test,
    )


# Global singleton
escaped_testing_detector = EscapedTestingDetector()
