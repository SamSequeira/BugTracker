"""
escaped_testing_detector.py
----------------------------
Feature 4: "Escaped Testing" Detection.

For a given bug in our demo repo, checks whether the existing test suite
covers the failing scenario detected by static analysis.  If no test covers
the path, it flags the issue as "escaped" and surfaces the test generated
by Feature 1 as the remediation for that coverage gap.

Design
------
This is intentionally a **single demo case** (PY_DIV_001 on
calculator.py), not a generalized coverage-analysis engine.

The detector:
  1. Inspects the existing test files near the flagged source file.
  2. Looks for test functions that exercise the specific function/rule
     combination that triggered the finding.
  3. If none are found: sets escaped=True and attaches a remediation
     message pointing at the generated test from Feature 1.

The check runs per-report and adds an "escaped_testing" field to
EnrichedBugReport.test_harness_result (or to a standalone dict
returned from ``check()``).
"""

from __future__ import annotations

import ast as pyast
import logging
import os
import re
from pathlib import Path
from typing import Any, Dict, List, Optional

logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Patterns that indicate coverage of a given rule in existing tests
# ---------------------------------------------------------------------------

# Maps rule_id → list of regex patterns that, if found in a test file,
# indicate the rule's scenario is already covered.
_COVERAGE_PATTERNS: Dict[str, List[str]] = {
    "PY_DIV_001": [
        r"ZeroDivisionError",
        r"divide\s*\(\s*\w+\s*,\s*0\s*\)",   # direct zero-arg call
        r"def test_.*divid",
        r"def test_.*zero",
    ],
    "PY_RES_001": [
        r"def test_.*file",
        r"open\(.*\)",
        r"\.close\(\)",
    ],
    "PY_EXC_001": [
        r"def test_.*except",
        r"def test_.*error",
        r"bare.*except",
    ],
    "PY_ASS_001": [
        r"def test_.*assert",
        r"AssertionError",
        r"ValueError.*required",
    ],
    "PY_MUT_001": [
        r"def test_.*default",
        r"def test_.*mutable",
        r"append_item",
    ],
    "JS_DIV_001": [
        r"divide.*0",
        r"Division by zero",
        r"toThrow",
    ],
    "JS_EQ_001": [
        r"===",
        r"toBe\(false\)",
        r"isAdmin.*'1'",
    ],
    "JS_AWA_001": [
        r"Promise\.all",
        r"processItems",
    ],
    "JAVA_DIV_001": [
        r"ArithmeticException",
        r"divide.*0",
    ],
    "JAVA_EXC_001": [
        r"catch.*Exception",
        r"empty.*catch",
    ],
    "JAVA_EQ_001": [
        r"assertEquals",
        r"\.equals\(",
    ],
    "JAVA_RES_001": [
        r"try-with-resources",
        r"AutoCloseable",
    ],
    "JAVA_INF_001": [
        r"timeout",
        r"infinite.*loop",
    ],
}


# ---------------------------------------------------------------------------
# Result dataclass
# ---------------------------------------------------------------------------

class EscapedTestingResult:
    """
    Result of the escaped-testing check for a single bug report.

    Attributes
    ----------
    escaped : bool
        True when no existing test covers the failing scenario.
    rule_id : str
        The rule that triggered the finding.
    file_path : str
        The source file that contains the bug.
    function_name : str | None
        The enclosing function, if known.
    coverage_found_in : list[str]
        Paths of test files that DO cover this scenario (empty when escaped).
    remediation : str
        Human-readable explanation of what to do, including a pointer to
        the generated test from Feature 1 when escaped=True.
    generated_test_source : str
        The test body generated by test_generation_service (if available).
    """

    def __init__(
        self,
        escaped: bool,
        rule_id: str,
        file_path: str,
        function_name: Optional[str],
        coverage_found_in: List[str],
        remediation: str,
        generated_test_source: str = "",
    ) -> None:
        self.escaped = escaped
        self.rule_id = rule_id
        self.file_path = file_path
        self.function_name = function_name
        self.coverage_found_in = coverage_found_in
        self.remediation = remediation
        self.generated_test_source = generated_test_source

    def to_dict(self) -> Dict[str, Any]:
        return {
            "escaped": self.escaped,
            "rule_id": self.rule_id,
            "file_path": self.file_path,
            "function_name": self.function_name,
            "coverage_found_in": self.coverage_found_in,
            "remediation": self.remediation,
            "generated_test_source": self.generated_test_source,
        }


# ---------------------------------------------------------------------------
# Detector
# ---------------------------------------------------------------------------

class EscapedTestingDetector:
    """
    Detects whether an existing bug's failing scenario is covered by any
    test in the surrounding codebase.

    If not covered → escaped=True, remediation points at the Feature 1
    generated test.
    """

    def check(
        self,
        rule_id: str,
        file_path: str,
        function_name: Optional[str] = None,
        repository_path: Optional[str] = None,
        generated_test_source: Optional[str] = None,
    ) -> EscapedTestingResult:
        """
        Check whether the bug scenario identified by ``rule_id`` in ``file_path``
        is already covered by an existing test file.

        Parameters
        ----------
        rule_id : str
            Static analysis rule that triggered (e.g. "PY_DIV_001").
        file_path : str
            Absolute or relative path to the flagged source file.
        function_name : str, optional
            Enclosing function, used for more targeted search.
        repository_path : str, optional
            Root of the repository; used to locate test directories.
        generated_test_source : str, optional
            The test body produced by Feature 1, surfaced when escaped=True.

        Returns
        -------
        EscapedTestingResult
        """
        patterns = _COVERAGE_PATTERNS.get(rule_id, [])
        test_files = self._locate_test_files(file_path, repository_path)
        coverage_found_in: List[str] = []

        for tf in test_files:
            if self._file_covers(tf, patterns, rule_id, function_name):
                coverage_found_in.append(tf)

        escaped = len(coverage_found_in) == 0

        if escaped:
            remediation = (
                f"No existing test covers the failing scenario for rule "
                f"'{rule_id}' in `{Path(file_path).name}`"
                + (f" (function `{function_name}`)" if function_name else "")
                + ". "
                f"The generated regression test (Feature 1) fills this gap — "
                f"add it to your test suite to prevent regressions."
            )
        else:
            covered_names = ", ".join(Path(f).name for f in coverage_found_in[:3])
            remediation = (
                f"Scenario for '{rule_id}' is already covered by: {covered_names}."
            )

        return EscapedTestingResult(
            escaped=escaped,
            rule_id=rule_id,
            file_path=file_path,
            function_name=function_name,
            coverage_found_in=coverage_found_in,
            remediation=remediation,
            generated_test_source=generated_test_source or "",
        )

    def check_report(self, report: Any) -> EscapedTestingResult:
        """
        Convenience wrapper that accepts an EnrichedBugReport (or its dict form)
        and runs the escaped-testing check, attaching the generated test source
        from the report's test_harness_result if present.
        """
        # Normalise to dict
        if hasattr(report, "model_dump"):
            r = report.model_dump(mode="json")
        elif isinstance(report, dict):
            r = report
        else:
            r = getattr(report, "__dict__", {})

        rule_id = (r.get("static_analysis") or {}).get("rule_id") or r.get("rule_id", "UNKNOWN")
        file_path = r.get("file_path") or r.get("file", "")
        function_name = r.get("function_name")
        repository_path = (r.get("repository") or {}).get("path") or r.get("repository_path")

        # Extract generated test source from Feature 1 harness result
        harness = r.get("test_harness_result") or {}
        gen_test = harness.get("generated_test_source", "") if isinstance(harness, dict) else ""

        return self.check(
            rule_id=rule_id,
            file_path=file_path,
            function_name=function_name,
            repository_path=repository_path,
            generated_test_source=gen_test,
        )

    # ------------------------------------------------------------------
    # Internal helpers
    # ------------------------------------------------------------------

    @staticmethod
    def _locate_test_files(
        source_file: str,
        repository_path: Optional[str],
    ) -> List[str]:
        """
        Find test files in the repository that might cover ``source_file``.

        Search strategy (in priority order):
        1. A test file whose name mirrors the source: ``test_<stem>.py``
        2. Any ``.py`` files inside a ``tests/`` or ``test/`` sibling directory.
        3. Any ``.py`` files at repository root whose name starts with ``test_``.
        """
        found: List[str] = []
        source_path = Path(source_file)
        stem = source_path.stem  # e.g. "calculator"

        search_roots: List[Path] = []

        # Add the source file's parent and its parents
        parent = source_path.parent
        if parent != Path("."):
            search_roots.append(parent)

        if repository_path:
            repo_root = Path(repository_path)
            search_roots.append(repo_root)
            # Add common test dir names
            for td in ("tests", "test", "__tests__", "spec"):
                td_path = repo_root / td
                if td_path.is_dir():
                    search_roots.append(td_path)

        seen: set = set()
        for root in search_roots:
            if not root.is_dir():
                continue
            try:
                for candidate in root.rglob("test_*.py"):
                    p = str(candidate)
                    if p not in seen:
                        seen.add(p)
                        found.append(p)
                # Also grab *_test.py and *.spec.js patterns
                for candidate in root.rglob("*_test.py"):
                    p = str(candidate)
                    if p not in seen:
                        seen.add(p)
                        found.append(p)
            except (PermissionError, OSError):
                continue

        # Prioritise the mirror file (test_<stem>.py)
        mirror_name = f"test_{stem}.py"
        found.sort(key=lambda p: (0 if Path(p).name == mirror_name else 1, p))

        return found

    @staticmethod
    def _file_covers(
        test_file: str,
        patterns: List[str],
        rule_id: str,
        function_name: Optional[str],
    ) -> bool:
        """
        Return True if ``test_file`` contains at least one of ``patterns``.
        Also matches if the file contains the function name directly.
        """
        try:
            content = Path(test_file).read_text(encoding="utf-8", errors="replace")
        except (OSError, PermissionError):
            return False

        # Check function name coverage
        if function_name and re.search(
            rf"\b{re.escape(function_name)}\b", content
        ):
            return True

        for pat in patterns:
            if re.search(pat, content, re.IGNORECASE):
                return True

        return False


